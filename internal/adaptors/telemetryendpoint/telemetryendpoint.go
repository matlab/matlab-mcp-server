package telemetryendpoint

import (
	"errors"
	"fmt"
	"net/url"
	"os"
	"strconv"
)

var (
	ErrEmptyEndpoint     = errors.New("telemetry collector endpoint is empty")
	ErrInvalidEndpoint   = errors.New("telemetry collector endpoint is not a valid URL")
	ErrUnsupportedScheme = errors.New("telemetry collector endpoint must use http or https")
	ErrMissingHost       = errors.New("telemetry collector endpoint has no host")
)

const generatedSource = `// Code generated by generate-telemetry-endpoint; DO NOT EDIT.

//go:build release

package defaultparameters

const defaultTelemetryCollectorEndpoint = %s
`

// Generate fails on an empty or malformed endpoint so a misconfigured release
// build never ships a binary that cannot reach the collector.
func Generate(outputPath, endpoint string) error {
	if err := validateEndpoint(endpoint); err != nil {
		return err
	}

	source := fmt.Sprintf(generatedSource, strconv.Quote(endpoint))
	if err := os.WriteFile(outputPath, []byte(source), 0o600); err != nil {
		return fmt.Errorf("writing %s: %w", outputPath, err)
	}

	return nil
}

func validateEndpoint(endpoint string) error {
	if endpoint == "" {
		return ErrEmptyEndpoint
	}

	parsed, err := url.Parse(endpoint)
	if err != nil {
		return ErrInvalidEndpoint
	}
	if parsed.Scheme != "http" && parsed.Scheme != "https" {
		return ErrUnsupportedScheme
	}
	if parsed.Host == "" {
		return ErrMissingHost
	}

	return nil
}
